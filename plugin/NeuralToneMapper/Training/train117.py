"""Fit the SDR RGB decoder on paired UE captures; leave camera 5 untouched."""
import sys,copy
from pathlib import Path
import cv2,numpy as np,torch
from torch import nn
from torch.nn import functional as F
root=Path(sys.argv[1]);out=Path(__file__).resolve().parents[1];torch.manual_seed(117)
def image(tag,i):
    a=cv2.imread(str(root/f'{tag}_{i}00000.png'))[:,:,::-1].copy()
    return torch.tensor(a,device='cuda',dtype=torch.float32)/255
def data(i):return torch.cat([image('input',i),image('feature',i)],-1),image('native',i)
class Decoder(nn.Module):
    def __init__(self):
        super().__init__();self.h=nn.Linear(6,24);self.o=nn.Linear(24,3)
    def forward(self,a):
        x=a[...,:3];v=self.o(F.relu(self.h(a)));return (x+v)*torch.clamp(x.amax(-1,keepdim=True)*128,0,1)
def run():
    net=Decoder().cuda();opt=torch.optim.AdamW(net.parameters(),lr=.003);ds=[data(i) for i in range(5)];best=1e9
    for k in range(1400):
        x,y=ds[k%4];r=torch.randint(4,445,(1536,),device='cuda');c=torch.randint(4,795,(1536,),device='cuda');dy=k%2;dx=1-dy
        a,b=x[r,c],y[r,c];an,bn=x[r+dy,c+dx],y[r+dy,c+dx];p=net(a);pn=net(an)
        err=p-b;dark=1+2*(b.mean(-1,keepdim=True)<.18);chroma=err-err.mean(-1,keepdim=True)
        loss=(err.abs()*dark).mean()+.35*chroma.abs().mean()+.35*((pn-p)-(bn-b)).abs().mean()+.1*err.mean(0).abs().mean();opt.zero_grad();loss.backward();opt.step()
        if k%25==0:
            with torch.no_grad():
                xv,yv=ds[4];e=(net(xv[::3,::3])-yv[::3,::3]).abs().mean().item()
                if e<best:best=e;state=copy.deepcopy(net.state_dict())
    net.load_state_dict(state);torch.save(state,out/'Training/ntm117_decoder.pt');print('validation',best,'gpu',torch.cuda.get_device_name())
    arr=lambda t:','.join(format(float(v),'.9e')+'f' for v in t.detach().cpu().reshape(-1))
    text='// Generated by Training/train117.py. Input: scene shaper + learned LLF RGB.\n'
    for name,t in [('H',net.h.weight),('HB',net.h.bias),('O',net.o.weight),('OB',net.o.bias)]:text+=f'static const float N117{name}[{t.numel()}]={{'+arr(t)+'};\n'
    (out/'Shaders/Private/NTMO117Weights.ush').write_text(text)
if __name__=='__main__':run()
